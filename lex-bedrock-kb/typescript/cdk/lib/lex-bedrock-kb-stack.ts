import * as cdk from 'aws-cdk-lib';
import * as bedrock from 'aws-cdk-lib/aws-bedrock';
import * as iam from 'aws-cdk-lib/aws-iam';
import * as lex from 'aws-cdk-lib/aws-lex';
import * as s3 from 'aws-cdk-lib/aws-s3';
import * as s3vectors from 'aws-cdk-lib/aws-s3vectors';
import { Construct } from 'constructs';

// Model ids in one place. Override with: cdk deploy -c generationModelId=<id> -c embeddingModelId=<id>
// Lex takes a foundation model ARN (not an inference profile), so the generation model must be
// invocable in the deployment Region without a cross-Region inference profile.
const GENERATION_MODEL_ID = 'amazon.nova-lite-v1:0';
const EMBEDDING_MODEL_ID = 'amazon.titan-embed-text-v2:0';
// Must match the output size of the embedding model (Titan Text Embeddings V2 supports 1024, 512, 256).
const EMBEDDING_DIMENSIONS = 1024;
const LOCALE_ID = 'en_US';

export class LexBedrockKbStack extends cdk.Stack {
  constructor(scope: Construct, id: string, props?: cdk.StackProps) {
    super(scope, id, props);

    const generationModelId = this.node.tryGetContext('generationModelId') ?? GENERATION_MODEL_ID;
    const embeddingModelId = this.node.tryGetContext('embeddingModelId') ?? EMBEDDING_MODEL_ID;
    const foundationModelArn = (modelId: string) =>
      `arn:${this.partition}:bedrock:${this.region}::foundation-model/${modelId}`;

    // Source documents. Private, TLS only, removed with the stack.
    const docsBucket = new s3.Bucket(this, 'DocsBucket', {
      blockPublicAccess: s3.BlockPublicAccess.BLOCK_ALL,
      encryption: s3.BucketEncryption.S3_MANAGED,
      enforceSSL: true,
      removalPolicy: cdk.RemovalPolicy.DESTROY,
      autoDeleteObjects: true,
    });

    // Vector store: S3 Vectors bucket and index (SSE-S3 by default). Names are generated by CloudFormation.
    const vectorBucket = new s3vectors.CfnVectorBucket(this, 'VectorBucket');
    vectorBucket.applyRemovalPolicy(cdk.RemovalPolicy.DESTROY);
    const vectorIndex = new s3vectors.CfnIndex(this, 'VectorIndex', {
      vectorBucketArn: vectorBucket.attrVectorBucketArn,
      dataType: 'float32',
      dimension: EMBEDDING_DIMENSIONS,
      distanceMetric: 'cosine',
      // Required for Bedrock Knowledge Bases: the chunk text and Bedrock metadata are not filterable.
      metadataConfiguration: { nonFilterableMetadataKeys: ['AMAZON_BEDROCK_TEXT', 'AMAZON_BEDROCK_METADATA'] },
    });
    vectorIndex.applyRemovalPolicy(cdk.RemovalPolicy.DESTROY);

    // Role used by the Knowledge Base to read the documents, embed them and write to the vector index.
    const kbRole = new iam.Role(this, 'KnowledgeBaseRole', {
      assumedBy: new iam.PrincipalWithConditions(new iam.ServicePrincipal('bedrock.amazonaws.com'), {
        StringEquals: { 'aws:SourceAccount': this.account },
        ArnLike: { 'aws:SourceArn': `arn:${this.partition}:bedrock:${this.region}:${this.account}:knowledge-base/*` },
      }),
      inlinePolicies: {
        KnowledgeBaseAccess: new iam.PolicyDocument({
          statements: [
            new iam.PolicyStatement({
              actions: ['bedrock:InvokeModel'],
              resources: [foundationModelArn(embeddingModelId)],
            }),
            new iam.PolicyStatement({
              actions: ['s3:ListBucket'],
              resources: [docsBucket.bucketArn],
              conditions: { StringEquals: { 'aws:ResourceAccount': this.account } },
            }),
            new iam.PolicyStatement({
              actions: ['s3:GetObject'],
              resources: [docsBucket.arnForObjects('docs/*')],
              conditions: { StringEquals: { 'aws:ResourceAccount': this.account } },
            }),
            new iam.PolicyStatement({
              actions: ['s3vectors:PutVectors', 's3vectors:GetVectors', 's3vectors:DeleteVectors',
                's3vectors:QueryVectors', 's3vectors:GetIndex'],
              resources: [vectorIndex.attrIndexArn],
            }),
          ],
        }),
      },
    });

    const knowledgeBase = new bedrock.CfnKnowledgeBase(this, 'KnowledgeBase', {
      name: `${this.stackName}-kb`,
      roleArn: kbRole.roleArn,
      knowledgeBaseConfiguration: {
        type: 'VECTOR',
        vectorKnowledgeBaseConfiguration: {
          embeddingModelArn: foundationModelArn(embeddingModelId),
          embeddingModelConfiguration: {
            bedrockEmbeddingModelConfiguration: { dimensions: EMBEDDING_DIMENSIONS, embeddingDataType: 'FLOAT32' },
          },
        },
      },
      storageConfiguration: {
        type: 'S3_VECTORS',
        s3VectorsConfiguration: { indexArn: vectorIndex.attrIndexArn },
      },
    });

    const dataSource = new bedrock.CfnDataSource(this, 'DataSource', {
      name: 'docs',
      knowledgeBaseId: knowledgeBase.attrKnowledgeBaseId,
      // RETAIN keeps stack deletion independent of the vector store; the vectors go with the index.
      dataDeletionPolicy: 'RETAIN',
      dataSourceConfiguration: {
        type: 'S3',
        s3Configuration: { bucketArn: docsBucket.bucketArn, inclusionPrefixes: ['docs/'] },
      },
    });

    // Role used by Lex at runtime: call the generation model and retrieve from this one Knowledge Base.
    const lexRole = new iam.Role(this, 'LexBotRole', {
      assumedBy: new iam.PrincipalWithConditions(new iam.ServicePrincipal('lexv2.amazonaws.com'), {
        StringEquals: { 'aws:SourceAccount': this.account },
        ArnLike: {
          'aws:SourceArn': [
            `arn:${this.partition}:lex:${this.region}:${this.account}:bot/*`,
            `arn:${this.partition}:lex:${this.region}:${this.account}:bot-alias/*`,
          ],
        },
      }),
      inlinePolicies: {
        QnaIntentAccess: new iam.PolicyDocument({
          statements: [
            new iam.PolicyStatement({
              actions: ['bedrock:InvokeModel'],
              resources: [foundationModelArn(generationModelId)],
            }),
            new iam.PolicyStatement({
              actions: ['bedrock:Retrieve'],
              resources: [knowledgeBase.attrKnowledgeBaseArn],
            }),
          ],
        }),
      },
    });

    // Lex bot with the built-in AMAZON.QnAIntent. Utterances that match no other intent go to it.
    // Lex adds an AMAZON.FallbackIntent to every locale; it is declared here so that the template lists all intents.
    // The bot is built from the DRAFT version and tested with TestBotAlias.
    const bot = new lex.CfnBot(this, 'Bot', {
      name: `${this.stackName}-bot`,
      roleArn: lexRole.roleArn,
      dataPrivacy: { ChildDirected: false },
      idleSessionTtlInSeconds: 300,
      autoBuildBotLocales: true,
      botLocales: [{
        localeId: LOCALE_ID,
        nluConfidenceThreshold: 0.4,
        intents: [
          {
            name: 'QnAIntent',
            parentIntentSignature: 'AMAZON.QnAIntent',
            qnAIntentConfiguration: {
              bedrockModelConfiguration: { modelArn: foundationModelArn(generationModelId) },
              dataSourceConfiguration: {
                bedrockKnowledgeStoreConfiguration: {
                  bedrockKnowledgeBaseArn: knowledgeBase.attrKnowledgeBaseArn,
                  // Lex rejects the import when this is left unset. false = generate the answer with the model.
                  exactResponse: false,
                },
              },
            },
          },
          { name: 'FallbackIntent', parentIntentSignature: 'AMAZON.FallbackIntent' },
        ],
      }],
    });

    new cdk.CfnOutput(this, 'DocsBucketName', { value: docsBucket.bucketName });
    new cdk.CfnOutput(this, 'KnowledgeBaseId', { value: knowledgeBase.attrKnowledgeBaseId });
    new cdk.CfnOutput(this, 'DataSourceId', { value: dataSource.attrDataSourceId });
    new cdk.CfnOutput(this, 'BotId', { value: bot.attrId });
    new cdk.CfnOutput(this, 'LocaleId', { value: LOCALE_ID });
    new cdk.CfnOutput(this, 'GenerationModelId', { value: generationModelId });
  }
}
